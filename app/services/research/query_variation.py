"""Query variation generation for evidence-first multi-search research.

This module provides deterministic, bounded query variation generation to ensure
broad search discovery before entity resolution is finalized.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional, Set


